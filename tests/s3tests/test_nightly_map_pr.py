"""Self-tests for nightly_map_diff.py.

    python3 tests/s3tests/test_nightly_map_pr.py
"""
import os
import sys
import tempfile
import unittest

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import nightly_map_diff as nmd  # noqa: E402


BASE_MAP = """# ceph s3-tests: the conformance map

Generated by `tests/s3tests/conformance_map.py` from ceph/s3-tests 5b39871, run 10000000001. Do not edit by hand.

760 test functions: 236 pass, 430 fail, 94 skipped, 0 unknown. The nightly job counts parametrized cases, so its totals are higher.

| area | owner | design section | pass | fail | skip |
|---|---|---|---|---|---|
| checksums | #117 | 7.1 | 0 | 11 | 0 |
| versioning | #113 | 6.5 | 18 | 4 | 0 |

## checksums: 11 not passing

- `test_object_checksum_sha256` (fail): assert 400 == 200
"""

SAME_COUNTS_NEW_RUN = """# ceph s3-tests: the conformance map

Generated by `tests/s3tests/conformance_map.py` from ceph/s3-tests 5b39871, run 20000000002 (2026-11-19). Do not edit by hand.

760 test functions: 236 pass, 430 fail, 94 skipped, 0 unknown. The nightly job counts parametrized cases, so its totals are higher.

| area | owner | design section | pass | fail | skip |
|---|---|---|---|---|---|
| checksums | #117 | 7.1 | 0 | 11 | 0 |
| versioning | #113 | 6.5 | 18 | 4 | 0 |

## checksums: 11 not passing

- `test_object_checksum_sha256` (fail): different failure message
"""


class NightlyMapDiffTest(unittest.TestCase):
    def test_same_counts_different_run_id_gives_no_change(self):
        self.assertFalse(nmd.counts_differ(BASE_MAP, SAME_COUNTS_NEW_RUN))

    def test_ignores_table_like_lines_after_section_heading(self):
        with_pipes = SAME_COUNTS_NEW_RUN + "| bogus | a | b | 1 | 2 | 3 |\n"
        self.assertFalse(nmd.counts_differ(BASE_MAP, with_pipes))

    def test_changed_area_count_gives_change(self):
        updated = BASE_MAP.replace(
            "| checksums | #117 | 7.1 | 0 | 11 | 0 |",
            "| checksums | #117 | 7.1 | 6 | 5 | 0 |",
        ).replace(
            "760 test functions: 236 pass, 430 fail, 94 skipped, 0 unknown.",
            "760 test functions: 242 pass, 424 fail, 94 skipped, 0 unknown.",
        )
        self.assertTrue(nmd.counts_differ(BASE_MAP, updated))

    def test_changed_area_only_with_same_totals_gives_change(self):
        swapped = BASE_MAP.replace(
            "| checksums | #117 | 7.1 | 0 | 11 | 0 |",
            "| checksums | #117 | 7.1 | 1 | 10 | 0 |",
        ).replace(
            "| versioning | #113 | 6.5 | 18 | 4 | 0 |",
            "| versioning | #113 | 6.5 | 17 | 5 | 0 |",
        )
        self.assertTrue(nmd.counts_differ(BASE_MAP, swapped))

    def test_changed_total_only_gives_change(self):
        shifted = BASE_MAP.replace(
            "760 test functions: 236 pass, 430 fail, 94 skipped, 0 unknown.",
            "760 test functions: 236 pass, 430 fail, 93 skipped, 1 unknown.",
        )
        self.assertTrue(nmd.counts_differ(BASE_MAP, shifted))

    def test_added_or_removed_area_row_gives_change(self):
        added = BASE_MAP.replace(
            "| versioning | #113 | 6.5 | 18 | 4 | 0 |",
            "| versioning | #113 | 6.5 | 18 | 4 | 0 |\n| cors | #116 | 7.2 | 1 | 11 | 0 |",
        )
        self.assertTrue(nmd.counts_differ(BASE_MAP, added))
        self.assertTrue(nmd.counts_differ(added, BASE_MAP))

    def test_malformed_map_raises(self):
        with self.assertRaises(ValueError):
            nmd.counts_differ(BASE_MAP, "# empty\n")

    def test_real_committed_map_with_new_run_id_gives_no_change(self):
        real_path = os.path.join(HERE, "CONFORMANCE_MAP.md")
        with open(real_path, encoding="utf-8") as fh:
            committed = fh.read()
        regenerated = committed.replace("43537724429", "99999999999")
        self.assertFalse(nmd.counts_differ(committed, regenerated))

    def test_cli_github_output(self):
        with tempfile.TemporaryDirectory() as d:
            old_p = os.path.join(d, "old.md")
            same_p = os.path.join(d, "same.md")
            diff_p = os.path.join(d, "diff.md")
            bad_p = os.path.join(d, "bad.md")
            gh_out = os.path.join(d, "gh_out.txt")

            with open(old_p, "w", encoding="utf-8") as fh:
                fh.write(BASE_MAP)
            with open(same_p, "w", encoding="utf-8") as fh:
                fh.write(SAME_COUNTS_NEW_RUN)
            with open(diff_p, "w", encoding="utf-8") as fh:
                fh.write(
                    BASE_MAP.replace(
                        "| checksums | #117 | 7.1 | 0 | 11 | 0 |",
                        "| checksums | #117 | 7.1 | 6 | 5 | 0 |",
                    )
                )
            with open(bad_p, "w", encoding="utf-8") as fh:
                fh.write("not a map\n")

            self.assertEqual(nmd.main([old_p, same_p, "--github-output", gh_out]), 0)
            with open(gh_out, encoding="utf-8") as fh:
                self.assertEqual(fh.read().strip(), "changed=false")

            with open(gh_out, "w", encoding="utf-8") as fh:
                fh.write("")
            self.assertEqual(nmd.main([old_p, diff_p, "--github-output", gh_out]), 0)
            with open(gh_out, encoding="utf-8") as fh:
                self.assertEqual(fh.read().strip(), "changed=true")

            self.assertNotEqual(nmd.main([old_p, bad_p]), 0)


if __name__ == "__main__":
    unittest.main()
